def require_ledger() -> None:
    if not audit.ready:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Decision ledger is unavailable. Scoring still works; history does not.",
        )


@app.get("/api/v1/decisions", summary="Recent scoring decisions, newest first")
def list_decisions(
    limit: int = 50,
    offset: int = 0,
    only_actioned: bool = False,
) -> dict[str, Any]:
    """The alert queue.

    Each entry carries its latest analyst disposition, so a reviewer can see at a
    glance what has already been judged and what is still waiting.
    """
    require_ledger()
    return {"decisions": audit.recent_decisions(limit=limit, offset=offset,
                                                only_actioned=only_actioned)}


@app.get("/api/v1/decisions/{decision_id}", summary="Replay one decision in full")
def get_decision(decision_id: str) -> dict[str, Any]:
    """Everything recorded about one scoring event.

    This is the endpoint that makes the audit trail real: months after the fact, and
    after the model has been retrained, it returns the probability, the threshold and
    policy in force at the time, the model version that produced it, and every SHAP
    concept with its signed contribution.
    """
    require_ledger()
    record = audit.get_decision(decision_id)
    if record is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND,
                            detail=f"No decision {decision_id!r} in the ledger.")
    return record


@app.post("/api/v1/decisions/{decision_id}/disposition",
          status_code=status.HTTP_201_CREATED,
          summary="Record a reviewer's conclusion about an alert")
def add_disposition(decision_id: str, payload: DispositionRequest) -> dict[str, Any]:
    """Attach a human outcome to a decision.

    Written as a new row rather than an update: the model's decision stays immutable,
    and a reviewer who changes their mind adds another judgement instead of erasing
    the first. These rows are what `GET /api/v1/stats` computes reviewed precision from.
    """
    require_ledger()
    try:
        return audit.record_disposition(decision_id, payload.outcome,
                                        payload.reviewer, payload.note)
    except KeyError:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND,
                            detail=f"No decision {decision_id!r} in the ledger.") from None


@app.post("/api/v1/disputes", status_code=status.HTTP_201_CREATED,
          summary="Draft a representment packet for a disputed payment")
def raise_dispute(payload: DisputeRequest) -> dict[str, Any]:
    """Reconstruct the case from the ledger and draft the dispute response.

    The only endpoint in FinGuard that calls a language model, and it sits deliberately
    outside the decision path: the score was made by the Random Forest months ago and
    is not revisited here. The model assembles evidence into a document.

    It never fails for want of a model. No credentials, a timeout, a refusal, a
    response that does not validate - each falls back to a deterministic draft built
    from the same evidence, flagged `degraded: true`. A dispute has a filing deadline,
    and returning nothing because a third-party API was unreachable is the worse
    outcome by a wide margin.
    """
    require_ledger()
    try:
        result = respond_to_dispute(payload.decision_id, payload.dispute_reason, store=audit)
    except KeyError:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"No decision {payload.decision_id!r} in the ledger to dispute.",
        ) from None

    stored = audit.record_dispute(payload.decision_id, payload.dispute_reason, result["packet"])
    log.info("%s  dispute on %s -> %s (confidence %.2f, drafted by %s)",
             stored["dispute_id"], payload.decision_id,
             result["packet"]["recommendation"], result["packet"]["confidence"],
             result["packet"]["generated_by"])

    return {**stored, **result}


@app.get("/api/v1/disputes/{dispute_id}", summary="Retrieve a drafted representment packet")
def get_dispute(dispute_id: str) -> dict[str, Any]:
    require_ledger()
    record = audit.get_dispute(dispute_id)
    if record is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND,
                            detail=f"No dispute {dispute_id!r} in the ledger.")
    return record


@app.get("/api/v1/stats", summary="Live operating summary")
def stats() -> dict[str, Any]:
    """Volume, block rate, rupees held, and precision over reviewed alerts only.

    Precision is reported against analyst dispositions rather than the training
    labels, because in production there are no labels - only outcomes a human
    eventually confirms. Alerts nobody has reviewed are excluded rather than assumed
    correct, which is why this number can differ from the one in the evaluation report.
    """
    require_ledger()
    return audit.stats()


@app.get("/api/v1/health/deep", summary="Per-dependency status and the active rung")
def health_deep() -> dict[str, Any]:
    """Every dependency, and which rung the engine would answer on right now.

    The shallow probe answers "is it up". This answers "what is it currently able to
    do", which is the question that matters during a partial outage - and it is the
    difference between noticing a silent fallback and discovering it in a monthly
    report when the alert rate has moved.
    """
    ledger_state, recorded = _ledger_state()
    provider = available_provider()

    rung = Rung.FULL if (engine.ready and not engine.disabled) else Rung.RULES
    return {
        "rung": int(rung),
        "rung_label": rung.label,
        "serving": rung == Rung.FULL,
        "dependencies": {
            "model": {
                "status": "ok" if engine.ready and not engine.disabled else "unavailable",
                "name": engine.config.get("best_model") if engine.ready else None,
                "trained_at": engine.config.get("created_at") if engine.ready else None,
                "disabled_by_operator": engine.disabled,
            },
            "explainer": {"status": "ok" if engine.explainer is not None else "unavailable"},
            "rule_engine": {"status": "ok", "note": "always available - pure function, no artifacts"},
            "audit_ledger": {"status": ledger_state, "decisions_recorded": recorded,
                             "last_error": audit.last_error},
            "llm_provider": {
                "status": "configured" if provider else "absent",
                "provider": provider[0] if provider else None,
                "note": "absent means dispute packets are drafted from templates",
            },
        },
        "chaos_endpoint_enabled": CHAOS_ENABLED,
    }


@app.post("/api/v1/admin/chaos/model", include_in_schema=False,
          summary="Disable or restore the model, to exercise the ladder")
def chaos_model(disable: bool = True) -> dict[str, Any]:
    """Turn the primary scorer off and watch the fallback take over.

    Disabled unless FINGUARD_ENABLE_CHAOS is set. An unauthenticated endpoint that
    switches off fraud detection is not something that should exist by default, and
    the whole point of the ladder is that it works without anyone asking it to.
    """
    if not CHAOS_ENABLED:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Chaos endpoint disabled. Set FINGUARD_ENABLE_CHAOS=1 to enable it.",
        )
    engine.disabled = bool(disable)
    log.warning("Model %s by operator via chaos endpoint.",
                "DISABLED" if engine.disabled else "restored")
    return {"model_disabled": engine.disabled,
            "rung": Rung.RULES.label if engine.disabled else Rung.FULL.label}


