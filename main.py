"""FinGuard Module 4 - REST API.

Serves the Module 2 classifier and the Module 3 explanation layer over HTTP so the
React dashboard can score a transaction and show *why* it was scored that way.

    python main.py          # http://localhost:8080, docs at /docs

Three design decisions worth knowing before you read the code:

**The model is loaded once, at startup, not per request.** A 400-tree Random Forest
plus a SHAP TreeExplainer costs seconds to construct and single-digit milliseconds to
run. Building either inside the request handler would turn a 40 ms endpoint into a
4-second one.

**The API keeps a short per-sender history, and it has to.** Four of the model's
features are backward-looking: the gap since the sender's last payment, the size of
that payment, the ratio between them, and whether it went to the same receiver. Those
exist because the "Rs.1 test" scam is invisible in a single row - it is a Rs.1 probe
followed within seconds by a large transfer to the *same* receiver. Score one row in
isolation and `engineer_features` sees no predecessor, so it fills `prev_amount = 0`
and `prev_amount_ratio = amount`, which reads to the model as an enormous jump in
spending and pushes almost anything above the threshold. The history store is what
makes the two-request demo work: POST Rs.1, then POST Rs.50,000 to the same receiver,
and the second call is flagged for the sequence rather than the size. In production
this store is a Redis or feature-store lookup; here it is an in-memory dict with a
TTL, which is honest about being single-process.

**Explanations come from Module 3, not from a reimplementation.** The endpoint calls
`explain_transaction` directly, so the JSON the dashboard renders and the audit report
on disk are generated by the same code path. SHAP values are aggregated by *concept*
before they leave the process, which is why the dashboard receives "age of the
receiving UPI ID" once rather than four correlated columns splitting credit between
them.

**The decision is merchant-side and has three outcomes, not two.** The model returns a
probability; `merchant_policy` turns it into ACCEPT, STEP_UP or HOLD by comparing the
expected rupee cost of each action under the merchant's own economics. A gateway can
challenge a payment with 3-D Secure - an option a bank protecting a consumer does not
have - and a two-outcome API cannot express it. `status` is still emitted as
BLOCKED/APPROVED so existing callers keep working.
"""

