if __name__ == "__main__":
    import socket

    import uvicorn

    def _port_is_free(host: str, port: int) -> bool:
        if port == 0:
            return True
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
            probe.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            return probe.connect_ex(("127.0.0.1", port)) != 0

    if not _port_is_free(HOST, PORT):
        # Checked before uvicorn binds, so the message names the fix rather than
        # surfacing an OSError from deep inside the server's startup path.
        log.error("Port %d is already in use. Start on another one with "
                  "FINGUARD_PORT=8090 python main.py, and point the dashboard at it "
                  "with VITE_API_BASE_URL=http://localhost:8090.", PORT)
        raise SystemExit(1)

    # reload=False on purpose: the reloader would re-import the module and rebuild
    # the 400-tree explainer on every file save.
    uvicorn.run(app, host=HOST, port=PORT, log_level="info")
